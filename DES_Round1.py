# ============================================================

def sbox_function(bits):

    result = ""

    print("\n---------------- S BOX ----------------")

    for i in range(8):

        block = bits[i * 6:(i + 1) * 6]

        # Row = first and last bit
        row = int(block[0] + block[5], 2)

        # Column = middle 4 bits
        column = int(block[1:5], 2)

        value = S_BOX[i][row][column]

        output = format(value, "04b")

        print(
            "S" + str(i + 1),
            "Input =", block,
            "Row =", row,
            "Column =", column,
            "Value =", value,
            "Output =", output
        )

        result += output

    return result


