RCON = [
    0x00, 0x01, 0x02, 0x04, 0x08,
    0x10, 0x20, 0x40, 0x80, 0x1B, 0x36
]


def print_state(title, state):
    print("\n" + title)

    for row in state:
        print(" ".join(f"{x:02X}" for x in row))


def sub_bytes(state):
    return [
        [S_BOX[x >> 4][x & 0x0F] for x in row]
        for row in state
    ]


def shift_rows(state):
    return [
        state[0],
        state[1][1:] + state[1][:1],
        state[2][2:] + state[2][:2],
        state[3][3:] + state[3][:3]
    ]


def gmul(a, b):
    result = 0

    for _ in range(8):
        if b & 1:
            result ^= a

        high_bit = a & 0x80
        a = (a << 1) & 0xFF

        if high_bit:
            a ^= 0x1B

        b >>= 1

    return result


def mix_columns(state):
    result = [[0 for _ in range(4)] for _ in range(4)]

    for c in range(4):
        a0 = state[0][c]
        a1 = state[1][c]
        a2 = state[2][c]
        a3 = state[3][c]

        result[0][c] = gmul(a0, 2) ^ gmul(a1, 3) ^ a2 ^ a3
        result[1][c] = a0 ^ gmul(a1, 2) ^ gmul(a2, 3) ^ a3
        result[2][c] = a0 ^ a1 ^ gmul(a2, 2) ^ gmul(a3, 3)
        result[3][c] = gmul(a0, 3) ^ a1 ^ a2 ^ gmul(a3, 2)

    return result


def add_round_key(state, round_key):
    return [
        [state[r][c] ^ round_key[r][c] for c in range(4)]
        for r in range(4)
    ]


def key_expansion(key):
    words = []

    for c in range(4):
        words.append([
            key[0][c],
            key[1][c],
            key[2][c],
            key[3][c]
        ])

    for i in range(4, 44):
        temp = words[i - 1].copy()

        if i % 4 == 0:
            temp = temp[1:] + temp[:1]

            for j in range(4):
                temp[j] = S_BOX[temp[j] >> 4][temp[j] & 0x0F]

            temp[0] ^= RCON[i // 4]

        new_word = [
            words[i - 4][j] ^ temp[j]
            for j in range(4)
        ]

        words.append(new_word)

    round_keys = []

    for round_number in range(11):
        round_key = [
            [0 for _ in range(4)]
            for _ in range(4)
        ]

        for c in range(4):
            word = words[round_number * 4 + c]

            for r in range(4):
                round_key[r][c] = word[r]

        round_keys.append(round_key)

    return round_keys


